// Helper to filter hospitals by division or district
export const getHospitalsByDivision = (division) => {
  if (!division || division === 'ALL') return BANGLADESH_HOSPITALS;
  return BANGLADESH_HOSPITALS.filter(
    (h) => h.division.toLowerCase() === division.toLowerCase()
  );
};

export const getHospitalsByDistrict = (district) => {
  if (!district || district === 'ALL') return BANGLADESH_HOSPITALS;
  return BANGLADESH_HOSPITALS.filter(
    (h) => h.district.toLowerCase() === district.toLowerCase()
  );
};

// Search across hospitals
export const searchHospitals = (query) => {
  if (!query || !query.trim()) return BANGLADESH_HOSPITALS;
  const q = query.toLowerCase().trim();
  return BANGLADESH_HOSPITALS.filter(
    (h) =>
      h.name.toLowerCase().includes(q) ||
      (h.bnName && h.bnName.includes(q)) ||
      h.district.toLowerCase().includes(q) ||
      h.upazila.toLowerCase().includes(q) ||
      h.address.toLowerCase().includes(q) ||
      h.type.toLowerCase().includes(q)
  );
};

// Generate direct Google Maps search and driving direction URL
export const getHospitalGoogleMapsUrl = (hospital) => {
  if (!hospital) return 'https://maps.google.com';
  if (hospital.lat && hospital.lng) {
    return `https://www.google.com/maps/dir/?api=1&destination=${hospital.lat},${hospital.lng}&travelmode=driving`;
  }
  return `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(hospital.name + ', ' + hospital.address + ', Bangladesh')}`;
};
